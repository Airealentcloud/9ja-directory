import fs from 'node:fs'
import path from 'node:path'
import vm from 'node:vm'
import process from 'node:process'
import ts from 'typescript'

const root = process.cwd()
const sourcePath = path.join(root, 'lib', 'blog-data.ts')
const outputPath = path.join(root, 'lib', 'blog-index-data.ts')
const args = new Set(process.argv.slice(2))

const mojibakeMarkers = ['â€', 'â‚', 'â”', 'â˜', 'â†', 'âœ', 'â', 'Ã', 'Â', 'ðŸ']

const windows1252Bytes = new Map([
  [0x20ac, 0x80], [0x0081, 0x81], [0x201a, 0x82], [0x0192, 0x83],
  [0x201e, 0x84], [0x2026, 0x85], [0x2020, 0x86], [0x2021, 0x87],
  [0x02c6, 0x88], [0x2030, 0x89], [0x0160, 0x8a], [0x2039, 0x8b],
  [0x0152, 0x8c], [0x008d, 0x8d], [0x017d, 0x8e], [0x008f, 0x8f],
  [0x0090, 0x90], [0x2018, 0x91], [0x2019, 0x92], [0x201c, 0x93],
  [0x201d, 0x94], [0x2022, 0x95], [0x2013, 0x96], [0x2014, 0x97],
  [0x02dc, 0x98], [0x2122, 0x99], [0x0161, 0x9a], [0x203a, 0x9b],
  [0x0153, 0x9c], [0x009d, 0x9d], [0x017e, 0x9e], [0x0178, 0x9f],
])

function hasMojibake(source) {
  return mojibakeMarkers.some((marker) => source.includes(marker)) || source.includes('\ufffd')
}

function recoverUtf8FromWindows1252(source) {
  const bytes = []

  for (const character of source.replace(/^\ufeff/, '')) {
    const codePoint = character.codePointAt(0)
    if (codePoint <= 0x7f || (codePoint >= 0xa0 && codePoint <= 0xff)) {
      bytes.push(codePoint)
      continue
    }

    if (windows1252Bytes.has(codePoint)) {
      bytes.push(windows1252Bytes.get(codePoint))
      continue
    }

    throw new Error(
      `Cannot safely repair ${sourcePath}: character U+${codePoint.toString(16).toUpperCase()} is not Windows-1252.`,
    )
  }

  return new TextDecoder('utf-8', { fatal: true }).decode(Uint8Array.from(bytes))
}

function evaluateBlogPosts(source, filename) {
  const transpiled = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
    fileName: filename,
    reportDiagnostics: true,
  })

  const errors = (transpiled.diagnostics || []).filter(
    (diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error,
  )
  if (errors.length > 0) {
    throw new Error(ts.formatDiagnosticsWithColorAndContext(errors, {
      getCanonicalFileName: (fileName) => fileName,
      getCurrentDirectory: () => root,
      getNewLine: () => '\n',
    }))
  }

  const module = { exports: {} }
  vm.runInNewContext(transpiled.outputText, {
    module,
    exports: module.exports,
    console,
  }, { filename })

  const posts = module.exports.blogPosts
  if (!Array.isArray(posts) || posts.length === 0) {
    throw new Error(`No blogPosts array was exported by ${filename}.`)
  }

  return posts
}

function getPostTime(date) {
  const time = Date.parse(date)
  return Number.isNaN(time) ? 0 : time
}

function renderIndex(posts) {
  const summaries = posts
    .map(({ slug, title, excerpt, image, date, author, category, readTime }) => ({
      slug,
      title,
      excerpt,
      image,
      date,
      author,
      category,
      readTime,
    }))
    .sort((a, b) => getPostTime(b.date) - getPostTime(a.date))

  return `// Generated by scripts/generate-blog-index.mjs. Do not edit manually.\n\n` +
    `export interface BlogPostSummary {\n` +
    `  slug: string\n` +
    `  title: string\n` +
    `  excerpt: string\n` +
    `  image: string\n` +
    `  date: string\n` +
    `  author: string\n` +
    `  category: string\n` +
    `  readTime: string\n` +
    `}\n\n` +
    `export const blogPostSummaries = ${JSON.stringify(summaries, null, 2)} as const satisfies readonly BlogPostSummary[]\n`
}

let source = fs.readFileSync(sourcePath, 'utf8')

if (args.has('--repair-encoding')) {
  if (!hasMojibake(source)) {
    console.log('Blog source has no known mojibake markers; no encoding repair was needed.')
  } else {
    const repaired = recoverUtf8FromWindows1252(source)
    if (hasMojibake(repaired)) {
      throw new Error('Encoding repair left known mojibake markers in the blog source.')
    }
    evaluateBlogPosts(repaired, sourcePath)
    fs.writeFileSync(sourcePath, repaired, 'utf8')
    source = repaired
    console.log('Repaired the blog source from Windows-1252 mojibake to UTF-8.')
  }
}

const generated = renderIndex(evaluateBlogPosts(source, sourcePath))

if (args.has('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : ''
  if (current !== generated) {
    console.error('Blog index is missing or stale. Run: npm run blog:index')
    process.exitCode = 1
  } else {
    console.log('Blog index is current.')
  }
} else {
  fs.writeFileSync(outputPath, generated, 'utf8')
  console.log(`Generated ${path.relative(root, outputPath)}.`)
}
